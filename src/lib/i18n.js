export const dictionaries = { en, ru, tr };
export const languages = ["en", "ru", "tr"];

let lang = "en";

export function resolveLanguage(setting) {
  if (languages.includes(setting)) return setting;
  const ui = String((ext && ext.i18n && ext.i18n.getUILanguage && ext.i18n.getUILanguage()) || navigator.language || "en").toLowerCase();
  const base = ui.split(/[-_]/)[0];
  if (languages.includes(base)) return base;
  // Russian is the closest familiar language for most CIS users.
  if (["uk", "be", "kk", "ky", "uz", "tg", "hy", "az", "ka"].includes(base)) return base === "az" ? "tr" : "ru";
  return "en";
}

export function setLanguage(setting) {
  lang = resolveLanguage(setting);
  return lang;
}

export function language() {
  return lang;
}

export function t(key, vars) {
  let s = (dictionaries[lang] && dictionaries[lang][key]) || en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// tn picks the plural form of `key` for n ("key.one", "key.few", ...; English
// and Turkish use one/other, Russian one/few/many) and fills {n}.
export function tn(key, n, vars = {}) {
  let form = "other";
  try {
    form = new Intl.PluralRules(lang).select(n);
  } catch {
    form = n === 1 ? "one" : "other";
  }
  const k = `${key}.${form}`;
  return t(k in en ? k : `${key}.other`, { ...vars, n });
}

export function errorText(code) {
  const key = "err." + code;
  return en[key] ? t(key) : t("err.ERROR");
}
